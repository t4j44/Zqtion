create table if not exists public.website_rate_limits (
  key_hash text not null,
  window_start timestamptz not null,
  attempt_count integer not null default 1 check (attempt_count > 0),
  primary key (key_hash, window_start)
);

alter table public.website_rate_limits enable row level security;

create or replace function public.consume_website_inquiry_rate_limit(
  p_key_hash text,
  p_window_seconds integer default 600,
  p_max_attempts integer default 5
)
returns boolean
language plpgsql
security definer
set search_path = public
as $$
declare
  current_window timestamptz;
  current_attempts integer;
begin
  if p_key_hash is null or char_length(p_key_hash) < 32 then
    return false;
  end if;

  current_window := to_timestamp(
    floor(extract(epoch from now()) / greatest(p_window_seconds, 60)) * greatest(p_window_seconds, 60)
  );

  insert into public.website_rate_limits (key_hash, window_start, attempt_count)
  values (p_key_hash, current_window, 1)
  on conflict (key_hash, window_start)
  do update set attempt_count = public.website_rate_limits.attempt_count + 1
  returning attempt_count into current_attempts;

  if random() < 0.02 then
    delete from public.website_rate_limits where window_start < now() - interval '2 days';
  end if;

  return current_attempts <= greatest(p_max_attempts, 1);
end;
$$;

revoke all on table public.website_events from anon, authenticated;
revoke all on table public.website_rate_limits from anon, authenticated;
revoke all on function public.consume_website_inquiry_rate_limit(text, integer, integer) from public, anon, authenticated;
grant execute on function public.consume_website_inquiry_rate_limit(text, integer, integer) to service_role;

