  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  event_name text not null check (char_length(event_name) between 2 and 80),
  path text not null,
  session_id text,
  landing_path text,
  referrer text,
  utm_source text,
  utm_medium text,
  utm_campaign text,
  utm_content text,
